"""R-18 generator: synthetic DynLex programs of a requested size, in the kernel's style.

Throwaway spike code.

Each unit is one point-like record and the ten patterns a geometry kernel writes
over such a record:

    1  construct          7  compare (returns an integer ordering)
    2  add                8  min/max (componentwise, returns the squared diagonal)
    3  scale              9  lerp
    4  dot               10  a predicate returning a boolean
    5  cross
    6  squared length

Unit names are parameterised by the unit index so no two patterns collide and the
compiler's pattern table grows with the program. The trailing main block calls
every pattern of every unit exactly once and folds the results into a single
printed number, so nothing is dead-code eliminated.

The numeric constants baked into each unit are drawn from a seeded PRNG, so a
given (seed, unit count) pair always produces byte-identical source.

    python generate.py --lines 20000 --out build/scale_20000.dl

Default seed: 20260909.
"""

import argparse
import pathlib
import random

PRELUDE = """# Generated by generate.py — do not edit, do not commit.
# Synthetic kernel-shaped DynLex, {units} units, seed {seed}.

import lib/std.dl

function print real {{a floating-point number:message}}:
    execute:
        @intrinsic("discard", @intrinsic("variadic call", "libc", "printf", a 32 bit integer, 1, "%.17g\\n", message))
"""


def unit_source(index, rng):
    tag = f"u{index:05d}"
    a = round(rng.uniform(0.5, 2.5), 6)
    b = round(rng.uniform(0.5, 2.5), 6)
    c = round(rng.uniform(0.5, 2.5), 6)
    t = round(rng.uniform(0.1, 0.9), 6)
    eps = "0.000000001"
    return f"""
# --- unit {index} ---

class:
    patterns:
        a point {tag}
    members:
        x as a floating-point number
        y as a floating-point number
        z as a floating-point number

function a point {tag} at {{a floating-point number:px}}, {{a floating-point number:py}} and {{a floating-point number:pz}}:
    execute:
        return @intrinsic("construct", a point {tag}, px, py, pz)

function the sum {tag} of {{a point {tag}:left}} and {{a point {tag}:right}}:
    execute:
        return a point {tag} at (left's x + right's x), (left's y + right's y) and (left's z + right's z)

function the scaling {tag} of {{a point {tag}:value}} by {{a floating-point number:factor}}:
    execute:
        return a point {tag} at (value's x * factor), (value's y * factor) and (value's z * factor)

function the dot {tag} of {{a point {tag}:left}} and {{a point {tag}:right}}:
    execute:
        return (left's x * right's x) + ((left's y * right's y) + (left's z * right's z))

function the cross {tag} of {{a point {tag}:left}} and {{a point {tag}:right}}:
    execute:
        set cx to (left's y * right's z) - (left's z * right's y)
        set cy to (left's z * right's x) - (left's x * right's z)
        set cz to (left's x * right's y) - (left's y * right's x)
        return a point {tag} at cx, cy and cz

function the squared length {tag} of {{a point {tag}:value}}:
    execute:
        return the dot {tag} of value and value

function the ordering {tag} of {{a point {tag}:left}} and {{a point {tag}:right}}:
    execute:
        if (the squared length {tag} of left) < (the squared length {tag} of right):
            return (0 - 1) as a 64 bit integer
        if (the squared length {tag} of left) > (the squared length {tag} of right):
            return 1 as a 64 bit integer
        return 0 as a 64 bit integer

function the spread {tag} of {{a point {tag}:left}} and {{a point {tag}:right}}:
    execute:
        set dx to (the maximum of left's x and right's x) - (the minimum of left's x and right's x)
        set dy to (the maximum of left's y and right's y) - (the minimum of left's y and right's y)
        set dz to (the maximum of left's z and right's z) - (the minimum of left's z and right's z)
        return (dx * dx) + ((dy * dy) + (dz * dz))

function the blend {tag} of {{a point {tag}:left}} and {{a point {tag}:right}} at {{a floating-point number:amount}}:
    execute:
        set rest to 1.0 - amount
        return a point {tag} at ((left's x * rest) + (right's x * amount)), ((left's y * rest) + (right's y * amount)) and ((left's z * rest) + (right's z * amount))

function {{a point {tag}:value}} is degenerate {tag}:
    execute:
        if (the squared length {tag} of value) < {eps}:
            return true
        return false

function the report {tag}:
    execute:
        set first to a point {tag} at {a}, {b} and {c}
        set second to a point {tag} at {b}, {c} and {a}
        set total to the dot {tag} of first and second
        set total to total + (the squared length {tag} of (the sum {tag} of first and second))
        set total to total + (the squared length {tag} of (the scaling {tag} of first by {t}))
        set total to total + (the squared length {tag} of (the cross {tag} of first and second))
        set total to total + (the spread {tag} of first and second)
        set total to total + (the squared length {tag} of (the blend {tag} of first and second at {t}))
        set total to total + ((the ordering {tag} of first and second) as a floating-point number)
        set total to total + (1.0 if first is degenerate {tag}, else 0.0)
        return total
"""


def main_source(units):
    lines = ["", "# --- main ---", "", "set total to 0.0"]
    for index in range(units):
        lines.append(f"set total to total + the report u{index:05d}")
    lines.append("print real total")
    return "\n".join(lines) + "\n"


def build_source(units, seed):
    rng = random.Random(seed)
    parts = [PRELUDE.format(units=units, seed=seed)]
    for index in range(units):
        parts.append(unit_source(index, rng))
    parts.append(main_source(units))
    return "".join(parts)


def line_count(text):
    return len(text.splitlines())


def units_for_lines(target, seed):
    """Smallest unit count whose program reaches `target` lines."""
    probe = build_source(8, seed)
    base = line_count(build_source(0, seed))
    per_unit = (line_count(probe) - base) / 8.0
    guess = max(1, int(round((target - base) / per_unit)))
    while line_count(build_source(guess, seed)) < target:
        guess += 1
    while guess > 1 and line_count(build_source(guess - 1, seed)) >= target:
        guess -= 1
    return guess


def expected_total(units, seed):
    """The number the generated program prints, recomputed here in IEEE doubles.

    The operation order mirrors `the report {tag}` exactly, so this is an
    independent check on the compiled binary rather than a restatement of it.
    """
    rng = random.Random(seed)
    total = 0.0
    for _ in range(units):
        a = round(rng.uniform(0.5, 2.5), 6)
        b = round(rng.uniform(0.5, 2.5), 6)
        c = round(rng.uniform(0.5, 2.5), 6)
        t = round(rng.uniform(0.1, 0.9), 6)
        first = (a, b, c)
        second = (b, c, a)

        def dot(l, r):
            return (l[0] * r[0]) + ((l[1] * r[1]) + (l[2] * r[2]))

        def squared(v):
            return dot(v, v)

        unit = dot(first, second)
        unit = unit + squared((first[0] + second[0], first[1] + second[1], first[2] + second[2]))
        unit = unit + squared((first[0] * t, first[1] * t, first[2] * t))
        cross = (
            (first[1] * second[2]) - (first[2] * second[1]),
            (first[2] * second[0]) - (first[0] * second[2]),
            (first[0] * second[1]) - (first[1] * second[0]),
        )
        unit = unit + squared(cross)
        dx = max(first[0], second[0]) - min(first[0], second[0])
        dy = max(first[1], second[1]) - min(first[1], second[1])
        dz = max(first[2], second[2]) - min(first[2], second[2])
        unit = unit + ((dx * dx) + ((dy * dy) + (dz * dz)))
        rest = 1.0 - t
        blend = (
            (first[0] * rest) + (second[0] * t),
            (first[1] * rest) + (second[1] * t),
            (first[2] * rest) + (second[2] * t),
        )
        unit = unit + squared(blend)
        if squared(first) < squared(second):
            ordering = -1
        elif squared(first) > squared(second):
            ordering = 1
        else:
            ordering = 0
        unit = unit + float(ordering)
        unit = unit + (1.0 if squared(first) < 0.000000001 else 0.0)
        total = total + unit
    return total


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--lines", type=int, required=True, help="minimum line count to reach")
    parser.add_argument("--seed", type=int, default=20260909)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    units = units_for_lines(args.lines, args.seed)
    text = build_source(units, args.seed)
    path = pathlib.Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"units={units} lines={line_count(text)} seed={args.seed} path={path}")
    print(f"expected={expected_total(units, args.seed):.17g}")


if __name__ == "__main__":
    main()
