"""R-18 runner: generate, compile and time the 5k / 20k / 50k line programs.

Throwaway spike code.

    python run.py --dynlex ../../../dynlex/build/dynlex.exe

Generates each program with generate.py, compiles it with `-o`, records wall time
(five runs, median; a program whose first compile exceeds 90 s is compiled once), records
the compiler's peak working set, runs the produced binary and compares its output
to the value generate.py computes independently in Python.

Writes results/dynlex-scale.md. The generated .dl files land in build/ and are
not committed — regenerate them with the same seed.
"""

import argparse
import pathlib
import statistics
import subprocess
import sys
import time

import psutil

HERE = pathlib.Path(__file__).resolve().parent
BUILD = HERE / "build"
RESULTS = HERE / "results"

TARGETS = [5000, 20000, 50000]
RUNS = 5
SLOW_SECONDS = 90.0


def compile_once(dynlex, source, output):
    """Compile and return (seconds, peak working set bytes, stdout, returncode)."""
    started = time.perf_counter()
    proc = psutil.Popen(
        [str(dynlex), str(source), "-o", str(output)],
        cwd=str(HERE),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    peak = 0
    while proc.poll() is None:
        try:
            peak = max(peak, proc.memory_info().peak_wset)
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            break
        time.sleep(0.02)
    try:
        peak = max(peak, proc.memory_info().peak_wset)
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        pass
    out = proc.stdout.read()
    proc.stdout.close()
    code = proc.wait()
    return time.perf_counter() - started, peak, out, code


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dynlex", required=True)
    parser.add_argument("--seed", type=int, default=20260909)
    args = parser.parse_args()

    BUILD.mkdir(exist_ok=True)
    RESULTS.mkdir(exist_ok=True)

    rows = []
    for target in TARGETS:
        source = BUILD / f"scale_{target}.dl"
        binary = BUILD / f"scale_{target}.out"
        gen = subprocess.run(
            [sys.executable, "generate.py", "--lines", str(target), "--seed", str(args.seed), "--out", str(source)],
            cwd=str(HERE),
            capture_output=True,
            text=True,
        )
        if gen.returncode != 0:
            sys.exit(f"generate.py failed:\n{gen.stdout}\n{gen.stderr}")
        summary, expected = gen.stdout.strip().splitlines()
        fields = dict(part.split("=", 1) for part in summary.split(" ", 3)[:3])
        units = int(fields["units"])
        lines = int(fields["lines"])
        expected_value = expected.split("=", 1)[1]

        times = []
        peaks = []
        diagnostics = ""
        code = 0
        for run_index in range(RUNS):
            seconds, peak, out, code = compile_once(args.dynlex, source, binary)
            times.append(seconds)
            peaks.append(peak)
            diagnostics = out.strip()
            if code != 0:
                break
            if run_index == 0 and seconds > SLOW_SECONDS:
                break

        ran = False
        printed = ""
        if code == 0 and binary.exists():
            done = subprocess.run([str(binary)], cwd=str(HERE), capture_output=True, text=True)
            ran = done.returncode == 0
            printed = done.stdout.strip()

        rows.append(
            {
                "target": target,
                "units": units,
                "lines": lines,
                "times": times,
                "median": statistics.median(times),
                "peak_mb": max(peaks) / (1024 * 1024),
                "returncode": code,
                "diagnostics": diagnostics,
                "ran": ran,
                "printed": printed,
                "expected": expected_value,
                "matches": printed == expected_value,
            }
        )
        print(
            f"{lines} lines ({units} units): median {statistics.median(times):.2f} s, "
            f"peak {max(peaks) / (1024 * 1024):.0f} MB, runs={ran}, output matches={printed == expected_value}"
        )

    write_results(rows, args.seed)


def write_results(rows, seed):
    out = []
    out.append("# Raw results — R-18, DynLex compile time and memory at kernel scale\n")
    out.append("Generated by `run.py`. Every number in `FINDINGS.md` comes from a row here.\n")
    out.append(f"Generator seed: `{seed}`. Regenerate any program with")
    out.append("`python generate.py --lines <N> --seed " + str(seed) + " --out build/scale_<N>.dl`.\n")

    out.append("\n## Summary\n")
    out.append("| Lines | Units | Compile s (median) | Peak MB | Binary runs? | Output matches expected? |")
    out.append("|---:|---:|---:|---:|---|---|")
    for row in rows:
        out.append(
            f"| {row['lines']} | {row['units']} | {row['median']:.2f} | {row['peak_mb']:.0f} | "
            f"{'yes' if row['ran'] else 'NO'} | {'yes' if row['matches'] else 'NO'} |"
        )

    out.append("\n## Every compile run (seconds)\n")
    out.append("| Lines | runs | median |")
    out.append("|---:|---|---:|")
    for row in rows:
        runs = ", ".join(f"{t:.2f}" for t in row["times"])
        out.append(f"| {row['lines']} | {runs} | {row['median']:.2f} |")
    out.append("")
    out.append("A program whose first compile exceeds 90 s is compiled once rather than five times.")

    out.append("\n## Output check\n")
    out.append("`generate.py` recomputes the printed total in Python IEEE doubles, following the")
    out.append("same operation order as the generated `the report` patterns. This is an independent")
    out.append("check that the compiled program is correct, not only that it compiles.\n")
    out.append("| Lines | Expected | Printed |")
    out.append("|---:|---|---|")
    for row in rows:
        out.append(f"| {row['lines']} | `{row['expected']}` | `{row['printed']}` |")

    out.append("\n## Compiler diagnostics\n")
    for row in rows:
        text = row["diagnostics"] or "(none)"
        out.append(f"**{row['lines']} lines** — exit {row['returncode']}:\n")
        out.append("```")
        out.append(text)
        out.append("```\n")

    (RESULTS / "dynlex-scale.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
