"""Bundles BIM slice tests into one program, so that one compile runs them all.

Every test imports most of the editor, so compiling each alone costs minutes
and gigabytes; bundled, the libraries compile once. Each test's top-level
statements become a function, its own definitions stay as they are (a helper
two tests define alike is kept once), and the program prints "=== name"
before each test. The expected output is the tests' expected outputs under
the same headers.

    bundle_tests.py make ROOT BUNDLE test...        writes ROOT/BUNDLE.dl and its expected output;
                                                   each test is found as */tests/<test>.dl below ROOT
    bundle_tests.py split OUTPUT EXPECTED FOLDER     writes FOLDER/<test>.out, prints each result
"""
import string
import sys
from pathlib import Path


def find_test(root, name):
    """The test's source, <module>/tests/<name>.dl, outside the kernel and the tools."""
    for candidate in sorted(root.glob(f"*/tests/{name}.dl")) + sorted(root.glob(f"*/*/tests/{name}.dl")):
        parts = candidate.relative_to(root).parts
        if parts[0] not in ("tools", "build", "generated") and parts[:2] not in (("kernel", "tests"), ("kernel", "reference")):
            return candidate
    sys.exit(f"{name}: no */tests/{name}.dl under {root}")


def make(root, bundle, names):
    imports, definitions, runners, expected = [], [], [], []
    seen = {}
    words = ["q" + a + b for a in string.ascii_lowercase for b in string.ascii_lowercase]
    for index, name in enumerate(names):
        body, mode, blocks = [], "body", []
        source = find_test(root, name)
        for line in source.read_text().splitlines():
            if line.startswith("import "):
                if line not in imports:
                    imports.append(line)
                continue
            if line and not line[0].isspace():
                if line.startswith(("function ", "local function ", "class:")):
                    mode = "definition"
                    blocks.append([])
                elif not line.startswith("#") or mode == "body":
                    mode = "body"
            if mode == "definition":
                blocks[-1].append(line)
            else:
                body.append(line)
        # A helper two tests define alike is kept once; alike in name only is
        # an error. A class is known by its whole text.
        for block in blocks:
            text = "\n".join(block).rstrip()
            key = block[0] if block[0] != "class:" else text
            if key in seen:
                if seen[key] != text:
                    sys.exit(f"{name}: '{key}' differs from an earlier test's")
                continue
            seen[key] = text
            definitions.extend(block)
        word = words[index]
        runners.append((name, word))
        definitions += ["", f"# The test {name}.", f"function run bim bundled test {word}:", "    execute:"]
        definitions += [("        " + line) if line.strip() else "" for line in body if not line.startswith("# SPDX")]
        definitions.append("")
        known = source.with_name(f"{name}.expected.txt")
        expected.append(f"=== {name}")
        expected.append(known.read_text().removesuffix("\n") if known.exists() else "(no expected output yet)")
    program = ["# SPDX-License-Identifier: MPL-2.0", "# Generated by bundle_tests.py: " + " ".join(names)]
    program += imports + [""] + definitions + [""]
    for name, word in runners:
        program.append(f'print (the string form of "=== {name}") as a line')
        program.append(f"run bim bundled test {word}")
    (root / f"{bundle}.dl").write_text("\n".join(program) + "\n")
    (root / f"{bundle}.expected.txt").write_text("\n".join(expected) + "\n")


def sections(path):
    found, current = {}, None
    for line in Path(path).read_text().splitlines():
        if line.startswith("=== "):
            current = line[4:]
            found[current] = []
        elif current is not None:
            found[current].append(line)
    return found


def split(output, expected, folder):
    got, want = sections(output), sections(expected)
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    failed = False
    for test, lines in want.items():
        have = got.get(test)
        if have is None:
            print(f"{test} MISSING (the run stopped before it)")
            failed = True
            continue
        (folder / f"{test}.out").write_text("\n".join(have) + "\n")
        print(f"{test} {'PASS' if have == lines else 'FAIL'}")
        failed = failed or have != lines
    return 1 if failed else 0


if __name__ == "__main__":
    if sys.argv[1] == "make":
        make(Path(sys.argv[2]), sys.argv[3], sys.argv[4:])
    else:
        sys.exit(split(sys.argv[2], sys.argv[3], sys.argv[4]))
